        /// 주소로 위도·경도 찾기. matched 에 어느 지역 기준인지 돌려줌 (예: "부산 남구")
        public static bool TryLocate(string address, out double lat, out double lon, out string matched)
        {
            lat = lon = 0; matched = null;
            if (string.IsNullOrEmpty(address)) return false;
            address = address.Trim();
            if (address.StartsWith("(") && address.IndexOf(')') > 0) address = address.Substring(address.IndexOf(')') + 1);   // "(본교) 서울특별시 ..."
            var tok = address.Replace("(", " ").Replace(",", " ").Split(new[] { ' ' }, StringSplitOptions.RemoveEmptyEntries);
            if (tok.Length == 0) return false;

            string[] codes = null;
            foreach (var a in SidoAlias)
                if (tok[0].StartsWith(a[0])) { codes = a.Skip(1).ToArray(); break; }
            List<Entry> inSido = codes == null ? All : All.Where(e => codes.Contains(e.Sido)).ToList();
            Entry hit = null;

            // 1) 시 + 일반구 (예: 수원시 팔달구 → 수원시팔달구)
            if (tok.Length > 2) hit = inSido.FirstOrDefault(e => e.Name == tok[1] + tok[2]);
            // 2) 시·군·구
            if (hit == null && tok.Length > 1) hit = inSido.FirstOrDefault(e => e.Name == tok[1]);
            if (hit != null) { lat = hit.Lat; lon = hit.Lon; matched = tok[0] + " " + hit.Name; return true; }

            // 3) 일반구가 2018년 뒤에 생기거나 없어진 시: 같은 시의 항목 평균 (예: 부천시, 화성시)
            if (tok.Length > 1)
            {
                var group = inSido.Where(e => e.Name.StartsWith(tok[1])).ToList();
                if (group.Count > 0) return Avg(group, tok[0] + " " + tok[1], out lat, out lon, out matched);
            }
            // 4) 시도를 몰라도 이름이 하나뿐이면
            if (tok.Length > 1)
            {
                var any = All.Where(e => e.Name == tok[1]).ToList();
                if (any.Count == 1) { lat = any[0].Lat; lon = any[0].Lon; matched = tok[0] + " " + tok[1]; return true; }
            }
            // 5) 시도 전체 평균 (예: 세종특별자치시)
            if (codes != null && inSido.Count > 0) return Avg(inSido, tok[0], out lat, out lon, out matched);
            return false;
        }

        static bool Avg(List<Entry> list, string name, out double lat, out double lon, out string matched)
        {
            lat = list.Average(e => e.Lat); lon = list.Average(e => e.Lon); matched = name;
            return true;
        }
